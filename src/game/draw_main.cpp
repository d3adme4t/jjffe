void DrawBitmap(uint8_t* buffer, int x, int y, const uint8_t* bmpData, bool masked)
{
    if (!bmpData || x < -128 || x > 448 || y < -128 || y > 328) return;
    
    // Parse bitmap header
    uint8_t flags = bmpData[0];
    int16_t height = bmpData[1];
    int16_t width = (int16_t)(bmpData[2] | (bmpData[3] << 8));
    int16_t xOff = (int16_t)(bmpData[4] | (bmpData[5] << 8));
    int16_t yOff = (int16_t)(bmpData[6] | (bmpData[7] << 8));
    
    const uint8_t* pixels = bmpData + 8;
    
    // Adjust position by offset
    int drawX = x - xOff;
    int drawY = y - yOff;
    
    bool isMasked = masked || (flags & 1);
    
    for (int row = 0; row < height; row++) {
        int py = drawY + row;
        if (py < 0 || py >= 200) continue;
        
        for (int col = 0; col < width; col++) {
            int px = drawX + col;
            if (px < 0 || px >= 320) continue;
            
            uint8_t color = pixels[row * width + col];
            
            if (isMasked) {
                if (color != 0) {
                    buffer[py * 320 + px] = color;
                }
            } else {
                buffer[py * 320 + px] = color;
            }
        }
    }
}

void DrawCharSimple(uint8_t* buffer, int x, int y, char ch, uint8_t color)
{
    if (x < 0 || x > 312 || y < 0 || y > 192) return;
    
    int fontIdx = (unsigned char)ch;
    if (fontIdx >= 128) return;
    
    const uint8_t* charData = fontData[fontIdx];
    
    for (int row = 0; row < 8; row++) {
        uint8_t bits = charData[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                int px = x + col;
                int py = y + row;
                if (px >= 0 && px < 320 && py >= 0 && py < 200) {
                    buffer[py * 320 + px] = color;
                }
            }
        }
    }
}

void DrawCharLarge(uint8_t* buffer, int x, int y, char ch, uint8_t color)
{
    if (x < 0 || x > 304 || y < 0 || y > 184) return;
    
    int fontIdx = (unsigned char)ch;
    if (fontIdx >= 128) return;
    
    const uint8_t* charData = fontData[fontIdx];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = charData[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                for (int dy = 0; dy < 2; dy++) {
                    for (int dx = 0; dx < 2; dx++) {
                        int px = x + col * 2 + dx;
                        int py = y + row * 2 + dy;
                        if (px >= 0 && px < 320 && py >= 0 && py < 200) {
                            buffer[py * 320 + px] = color;
                        }
                    }
                }
            }
        }
    }
}

void DrawStringSimple(uint8_t* buffer, int x, int y, const char* str, uint8_t color)
{
    // Prefer the original FFE font (DATA_007750) on the live back buffer —
    // same glyphs ASM uses via FUNC_001583 / DrawChar.
    if (g_videoState && buffer == g_videoState->backBuffer && str) {
        DrawString(str, color, x, y);
        return;
    }
    int xPos = x;
    while (str && *str) {
        DrawCharSimple(buffer, xPos, y, *str, color);
        xPos += 8;
        str++;
    }
}

void DrawStringLarge(uint8_t* buffer, int x, int y, const char* str, uint8_t color)
{
    // ASM titles use the same proportional font (no 2× scale). Match that.
    DrawStringSimple(buffer, x, y, str, color);
}

void FillRect(uint8_t* buffer, int x, int y, int w, int h, uint8_t color)
{
    for (int row = y; row < y + h && row < 200; row++) {
        if (row < 0) continue;
        for (int col = x; col < x + w && col < 320; col++) {
            if (col < 0) continue;
            buffer[row * 320 + col] = color;
        }
    }
}

